INSERT INTO Nesto_sync (Tabla, ModificadoId, Usuario, FechaModificacion)
SELECT 'Productos', p.Producto, 'Republicar DLQ Odoo (NestoAPI#511)', GETDATE()
FROM @productos p
WHERE EXISTS (SELECT 1 FROM Productos x WITH (NOLOCK) WHERE x.Empresa = '1' AND x.Número = p.Producto)
  AND NOT EXISTS (SELECT 1 FROM Nesto_sync s WITH (NOLOCK) WHERE s.Tabla = 'Productos' AND s.ModificadoId = p.Producto AND s.Sincronizado IS NULL);

SELECT COUNT(*) AS Encolados FROM Nesto_sync WHERE Tabla = 'Productos' AND Usuario = 'Republicar DLQ Odoo (NestoAPI#511)' AND Sincronizado IS NULL;
