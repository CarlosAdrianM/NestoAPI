INSERT INTO dbo.ProductosCategoriasSecundarias (Empresa, Número, Orden, Grupo, SubGrupo, Usuario, [Fecha Modificación])
SELECT '1', p.Número,
       ROW_NUMBER() OVER (PARTITION BY p.Número ORDER BY c.Prio, c.Grupo, c.Sub),
       c.Grupo, c.Sub, 'Issue414 carga inicial', GETDATE()
FROM #carga c
INNER JOIN dbo.Productos p ON p.Empresa='1' AND p.Número = c.Ref
WHERE NOT EXISTS (SELECT 1 FROM dbo.ProductosCategoriasSecundarias x
                  WHERE x.Empresa='1' AND x.Número = p.Número);
SELECT @@ROWCOUNT AS ParesCargados;

