declare @kits as table (
       numero varchar(15) not null,
       numeroAsociado varchar(15) not null,
       stock int not null default(0),
       stockAsociado int not null default(0),
       cantidadKit int not null default(0)
)

insert into @kits (numero, numeroAsociado, cantidadKit)
select k.Número, k.NúmeroAsociado, k.Cantidad
from Productos as p inner join Kits as k
on p.Empresa = k.Empresa and p.Número = k.Número
where p.Empresa = '1' and p.Estado = 0

delete @kits 
from @kits as k inner join Productos as p
on p.Empresa = '1' and p.Número = k.numeroAsociado and p.Estado<0

update @kits set stock = e.stock
from (
select Número, SUM(cantidad) as stock from ExtractoProducto where Almacén in ('ALG') and Número in (select numero from @kits) group by Número
) as e inner join @kits as k
on e.Número = k.numero

update @kits set stockAsociado = e.stock
from (
select Número, SUM(cantidad) as stock from ExtractoProducto where Almacén in ('ALG') and Número in (select numeroAsociado from @kits) group by Número
) as e inner join @kits as k
on e.Número = k.numeroAsociado


