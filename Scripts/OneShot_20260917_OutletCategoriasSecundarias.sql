BEGIN
    RAISERROR ('Falta algún subgrupo Outlet en SubGruposProducto (COS/OUT, PEL/OUT, COS/OUM).', 16, 1);
    RETURN;
END;

-- ==== 2) Clasificar cada par ====
SELECT c.Ref, c.Grupo, c.Sub,
       CASE WHEN p.Número IS NULL THEN 'NO EXISTE EN PRODUCTOS'
            WHEN x.Número IS NOT NULL THEN 'YA LA TIENE'
            ELSE 'A INSERTAR' END AS Situacion,
       p.Estado
INTO #clasificados
FROM #carga c
LEFT JOIN dbo.Productos p ON p.Empresa = '1' AND p.Número = c.Ref
LEFT JOIN dbo.ProductosCategoriasSecundarias x
       ON x.Empresa = '1' AND x.Número = c.Ref AND x.Grupo = c.Grupo AND x.SubGrupo = c.Sub;

-- ==== 3) Informe previo ====
SELECT RTRIM(Grupo) + '/' + RTRIM(Sub) AS Categoria, Situacion, COUNT(*) AS Pares
FROM #clasificados
GROUP BY Grupo, Sub, Situacion
ORDER BY 1, 2;

SELECT Ref AS RefNoExisteEnNesto, RTRIM(Grupo) + '/' + RTRIM(Sub) AS Categoria
FROM #clasificados WHERE Situacion = 'NO EXISTE EN PRODUCTOS' ORDER BY 1;

SELECT c.Ref, RTRIM(c.Grupo) + '/' + RTRIM(c.Sub) AS Categoria, c.Estado,
       (SELECT COUNT(*) FROM dbo.ProductosCategoriasSecundarias x WHERE x.Empresa = '1' AND x.Número = c.Ref) AS CategoriasQueYaTiene
FROM #clasificados c WHERE c.Situacion = 'A INSERTAR' ORDER BY 2, 1;

IF @DryRun = 1
BEGIN
    PRINT 'DRY RUN: no se ha insertado nada. Poner @DryRun = 0 para aplicar.';
    DROP TABLE #clasificados; DROP TABLE #carga;
    RETURN;
END;

-- ==== 4) Inserción + encolado ====
BEGIN TRAN;

INSERT INTO dbo.ProductosCategoriasSecundarias (Empresa, Número, Orden, Grupo, SubGrupo, Usuario, [Fecha Modificación])
SELECT '1', c.Ref,
       ISNULL(m.MaxOrden, 0) + ROW_NUMBER() OVER (PARTITION BY c.Ref ORDER BY c.Grupo, c.Sub),
       c.Grupo, c.Sub, @Usuario, GETDATE()
FROM #clasificados c
LEFT JOIN (SELECT Número, MAX(Orden) AS MaxOrden
           FROM dbo.ProductosCategoriasSecundarias WHERE Empresa = '1' GROUP BY Número) m ON m.Número = c.Ref
WHERE c.Situacion = 'A INSERTAR';
PRINT 'Pares insertados: ' + CAST(@@ROWCOUNT AS varchar);

INSERT INTO dbo.Nesto_sync (Tabla, ModificadoId, Usuario, FechaModificacion)
SELECT DISTINCT 'Productos', c.Ref, @Usuario, GETDATE()
FROM #clasificados c
WHERE c.Situacion = 'A INSERTAR'
  AND NOT EXISTS (SELECT 1 FROM dbo.Nesto_sync ns
                  WHERE ns.Tabla = 'Productos' AND RTRIM(ns.ModificadoId) = c.Ref AND ns.Sincronizado IS NULL);
PRINT 'Encolados en Nesto_sync: ' + CAST(@@ROWCOUNT AS varchar);

COMMIT;

-- ==== 5) Resumen final ====
SELECT RTRIM(pcs.Grupo) + '/' + RTRIM(pcs.SubGrupo) AS Categoria, COUNT(*) AS Productos
FROM dbo.ProductosCategoriasSecundarias pcs
WHERE pcs.SubGrupo IN ('OUT', 'OUM')
GROUP BY pcs.Grupo, pcs.SubGrupo ORDER BY 1;

DROP TABLE #clasificados; DROP TABLE #carga;
